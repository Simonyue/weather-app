export function getWmoWeatherInfo(code: number, isDay: boolean = true): WmoWeatherInfo {
  const info = WMO_WEATHER_MAP[code] || {
    code,
    descriptionZh: '晴间多云',
    descriptionEn: 'Partly cloudy',
    iconName: 'CloudSun',
    isRain: false,
    isSnow: false,
    isThunder: false,
  };

  if (!isDay) {
    if (code === 0) return { ...info, iconName: 'Moon' };
    if (code === 1 || code === 2) return { ...info, iconName: 'CloudMoon' };
  }

  return info;
}
